"""Generates src/ui-touch/PredictWords.inc, predictive text's built-in dictionary.

    pip install wordfreq better_profanity
    python3 scripts/predict/gen_words.py

The words and their frequencies are wordfreq's English list (Robyn Speer et
al., https://github.com/rspeer/wordfreq; data CC-BY-SA 4.0), which is built
from subtitles, Reddit, Twitter, news and Wikipedia, so it knows chat words.
Profanity (better_profanity's list) is left out of suggestions. The mesh and
team words from PredictText.h's kBase are added with a frequency floor.

Layout: words sorted case-insensitively, front-coded in blocks of kBlock.
Each entry: [shared prefix length][suffix length][suffix bytes][zipf x 10].
The first entry of each block shares nothing, so a block's first word can be
read straight from kBlockOff for a binary search.
"""
import os, re, sys
from wordfreq import top_n_list, zipf_frequency
from better_profanity import profanity

N = int(os.environ.get("PREDICT_WORDS", "10000"))
BLOCK = 32
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "src", "ui-touch", "PredictWords.inc")
# The same dictionary as a file, for boards that keep it out of flash (the
# T-Display P4 downloads it: PREDICTIVE_TEXT.md), and what the firmware checks
# it against.
PWD = os.path.join(ROOT, "dictionaries", "words-en.pwd")
INFO = os.path.join(ROOT, "src", "ui-touch", "PredictWordsInfo.h")

profanity.load_censor_words()
bad = {str(w).lower() for w in profanity.CENSOR_WORDSET}

# Contractions typed without the apostrophe aren't words: left out, they're
# corrected ("dont" -> "don't"). Real words that look like one (its, ill, well,
# were, lets, id) stay.
NO_APOS = {"dont", "im", "ive", "thats", "didnt", "doesnt", "isnt", "wasnt", "couldnt",
           "wouldnt", "shouldnt", "cant", "wont", "youre", "theyre", "whats", "theres",
           "arent", "havent", "hasnt", "werent", "aint", "youll", "youve", "weve", "theyve",
           "hes", "shes", "itll", "thatll", "wouldve", "couldve", "shouldve", "lemme", "yall"}

def ok(w):
    if w in NO_APOS: return False
    if not re.fullmatch(r"[a-z]+(?:'[a-z]+)?", w): return False
    if len(w) >= 24: return False
    if len(w) == 1 and w not in ("a", "i"): return False
    if w in bad or w.replace("'", "") in bad: return False
    return True

CAPS = {"i": "I", "i'm": "I'm", "i'll": "I'll", "i've": "I've", "i'd": "I'd"}
for d in ["monday", "tuesday", "wednesday", "thursday", "friday", "saturday", "sunday",
          "january", "february", "april", "june", "july", "august", "september", "october",
          "november", "december", "english", "american", "canada", "seattle", "portland",
          "oregon", "washington", "tacoma", "spokane", "vancouver"]:
    CAPS[d] = d[0].upper() + d[1:]

words = {}
for w in top_n_list("en", N * 2):
    if len(words) >= N: break
    if ok(w): words[w] = zipf_frequency(w, "en")

# The mesh/team words in PredictText.h's kBase, at least as likely as an everyday word.
src = open(os.path.join(ROOT, "src", "ui-touch", "PredictText.h")).read()
m = re.search(r"kBase\[\] = \{(.*?)\};", src, re.S)
for w in re.findall(r'"([^"]+)"', m.group(1)) if m else []:
    lw = w.lower()
    if not re.fullmatch(r"[a-z']+", lw): continue
    if w != lw: CAPS[lw] = w
    words[lw] = max(words.get(lw, 0), zipf_frequency(lw, "en"), 4.5)
for extra in ["meshcore", "wadamesh", "mediamesh", "lora", "repeater", "repeaters", "advert",
              "adverts", "standalone", "companion", "icewatch", "cascadiamesh"]:
    words.setdefault(extra, 4.2)
CAPS.update({"meshcore": "MeshCore", "wadamesh": "Wadamesh", "mediamesh": "MediaMesh",
             "lora": "LoRa", "icewatch": "ICEWatch", "cascadiamesh": "CascadiaMesh"})

items = sorted(words.items(), key=lambda kv: kv[0])
data, offs = bytearray(), []
prev = ""
for i, (w, z) in enumerate(items):
    disp = CAPS.get(w, w)
    b = disp.encode()
    if i % BLOCK == 0:
        offs.append(len(data)); shared = 0
    else:
        pb = prev.encode(); shared = 0
        while shared < min(len(pb), len(b)) and pb[shared] == b[shared]: shared += 1
    suf = b[shared:]
    data += bytes([shared, len(suf)]) + suf + bytes([max(1, min(255, round(z * 10)))])
    prev = disp

with open(OUT, "w") as f:
    f.write("// SPDX-License-Identifier: CC-BY-SA-4.0\n")
    f.write("// Generated by scripts/predict/gen_words.py - do not edit.\n")
    f.write("// Words and frequencies: wordfreq (Robyn Speer et al.), CC-BY-SA 4.0,\n")
    f.write("// https://github.com/rspeer/wordfreq. Layout: see the script.\n")
    f.write("#pragma once\n#include <stdint.h>\nnamespace predict { namespace words {\n")
    f.write(f"constexpr int kCount = {len(items)};\nconstexpr int kBlock = {BLOCK};\n")
    f.write(f"constexpr int kBlocks = {len(offs)};\n")
    f.write("static const uint32_t kBlockOff[kBlocks] = {")
    f.write(",".join(str(o) for o in offs)); f.write("};\n")
    f.write(f"static const uint8_t kData[{len(data)}] = {{\n")
    for i in range(0, len(data), 24):
        f.write(",".join(str(x) for x in data[i:i + 24]) + ",\n")
    f.write("};\n}}  // namespace predict::words\n")

# The file: "PWD1", word count, block count (u32 LE each), the block offsets
# (u32 LE), the data.
import struct
img = b"PWD1" + struct.pack("<II", len(items), len(offs)) + b"".join(struct.pack("<I", o) for o in offs) + bytes(data)
os.makedirs(os.path.dirname(PWD), exist_ok=True)
open(PWD, "wb").write(img)
h = 0x811C9DC5                      # FNV-1a, 32 bit (predict::fnv1a)
for b in img:
    h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
with open(INFO, "w") as f:
    f.write("// SPDX-License-Identifier: GPL-3.0-or-later\n")
    f.write("// Generated by scripts/predict/gen_words.py - do not edit.\n")
    f.write("// The dictionary file (dictionaries/words-en.pwd) this firmware expects.\n")
    f.write("#pragma once\n#include <stdint.h>\nnamespace predict { namespace words {\n")
    f.write(f"constexpr uint32_t kFileBytes = {len(img)};\n")
    f.write(f"constexpr uint32_t kFileFnv = 0x{h:08X};\n")
    f.write(f"constexpr int kFileWords = {len(items)};\n")
    f.write("}}  // namespace predict::words\n")
print(f"{len(items)} words, {len(data)} bytes + {len(offs) * 4} index -> {OUT}; {len(img)} B -> {PWD}")
