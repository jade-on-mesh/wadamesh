#!/usr/bin/env bash
# Re-vendors dav1d (the AV1 decoder MeshCore Open TAK photos need) into lib/dav1d.
#
#   git clone --depth 1 --branch 1.5.1 https://github.com/videolan/dav1d /tmp/dav1d
#   scripts/vendor_dav1d.sh /tmp/dav1d
#
# Takes only the portable C decoder: 8-bit, no assembly, no tools. The *_tmpl.c
# files are compiled once per bit depth upstream (meson passes -DBITDEPTH=8);
# PlatformIO builds every .c with the same flags, so each template gets a tiny
# src/8bpc/<name>_8.c wrapper instead and the templates are filtered out.
# Local changes live in lib/dav1d/patches and are applied last.
set -euo pipefail

SRC=${1:?usage: vendor_dav1d.sh <dav1d checkout>}
ROOT=$(cd "$(dirname "$0")/.." && pwd)
DST="$ROOT/lib/dav1d"
VERSION=$(git -C "$SRC" describe --tags --long --always 2>/dev/null || echo unknown)

rm -rf "$DST/src" "$DST/include" "$DST/gen" "$DST/COPYING"
mkdir -p "$DST/src/8bpc" "$DST/include/dav1d" "$DST/include/common" "$DST/gen"

cp "$SRC"/COPYING "$DST/"
cp "$SRC"/include/dav1d/*.h "$DST/include/dav1d/"
cp "$SRC"/include/common/*.h "$DST/include/common/"
cp "$SRC"/src/*.c "$SRC"/src/*.h "$DST/src/"

for t in "$DST"/src/*_tmpl.c; do
  name=$(basename "$t" _tmpl.c)
  printf '// Generated by scripts/vendor_dav1d.sh: the 8-bit instance of %s_tmpl.c.\n#define BITDEPTH 8\n#include "src/%s_tmpl.c"\n' \
    "$name" "$name" > "$DST/src/8bpc/${name}_8.c"
done

printf '/* Generated by scripts/vendor_dav1d.sh */\n#define DAV1D_VERSION "%s"\n' "$VERSION" > "$DST/gen/vcs_version.h"

# What meson's configure produces for a bare-metal Xtensa target, trimmed to the
# options the sources read. HAVE_MEMALIGN is moot: patches route allocation
# through dav1d_ext_* (see DAV1D_EXTERNAL_ALLOC in src/mem.h).
cat > "$DST/gen/config.h" <<'EOF'
/* Generated by scripts/vendor_dav1d.sh: portable 8-bit decoder, no assembly. */
#pragma once
#define ARCH_AARCH64 0
#define ARCH_ARM 0
#define ARCH_LOONGARCH 0
#define ARCH_LOONGARCH32 0
#define ARCH_LOONGARCH64 0
#define ARCH_PPC64LE 0
#define ARCH_RISCV 0
#define ARCH_RV32 0
#define ARCH_RV64 0
#define ARCH_X86 0
#define ARCH_X86_32 0
#define ARCH_X86_64 0
#define CONFIG_16BPC 0
#define CONFIG_8BPC 1
#define CONFIG_LOG 0
#define CONFIG_MACOS_KPERF 0
#define ENDIANNESS_BIG 0
#define HAVE_ALIGNED_ALLOC 0
#define HAVE_ASM 0
#define HAVE_C11_GENERIC 1
#define HAVE_CLOCK_GETTIME 1
#define HAVE_DLSYM 0
#define HAVE_ELF_AUX_INFO 0
#define HAVE_GETAUXVAL 0
#define HAVE_IO_H 0
#define HAVE_MEMALIGN 0
#define HAVE_POSIX_MEMALIGN 1
#define HAVE_PTHREAD_GETAFFINITY_NP 0
#define HAVE_PTHREAD_NP_H 0
#define HAVE_PTHREAD_SETAFFINITY_NP 0
#define HAVE_PTHREAD_SETNAME_NP 0
#define HAVE_PTHREAD_SET_NAME_NP 0
#define HAVE_SYS_TYPES_H 1
#define HAVE_UNISTD_H 1
#define TRIM_DSP_FUNCTIONS 1
/* wadamesh: allocation hooks + heap tables (lib/dav1d/patches). */
#ifndef DAV1D_EXTERNAL_ALLOC
#define DAV1D_EXTERNAL_ALLOC 1
#endif
EOF

for p in "$DST"/patches/*.patch; do
  [ -e "$p" ] || continue
  patch -s -p1 -d "$DST" < "$p"
done

echo "dav1d $VERSION vendored into lib/dav1d"
