#!/usr/bin/env bash
# The map icons the MeshCore Open TAK app draws (Material Icons), as a 14 px
# LVGL font, so the device map shows the same icon for each thing as the app:
# team roles, team marker kinds, watched reports, contacts and shared pins.
# Writes src/ui-touch/map_icons_14.c; the glyph table is in map_icons.h.
#
# The outlined icons the app uses (shield_outlined, videocam_outlined,
# badge_outlined) come from the Outlined font and are moved to U+F8E0.. so they
# don't collide with the filled glyphs on the same codepoints.
set -euo pipefail

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
work=$(mktemp -d "${TMPDIR:-/tmp}/wadamesh-map-icons.XXXXXX")
trap 'rm -rf "$work"' EXIT

rev=49d4db35df873165d6bd6ba09b063c7dafbac2f4   # google/material-design-icons
base="https://raw.githubusercontent.com/google/material-design-icons/$rev/font"
fetch() {
  curl -fsSL --retry 3 "$base/$1" -o "$work/$1"
  local got
  got=$(sha256sum "$work/$1" | awk '{print $1}')
  [[ $got == "$2" ]] || { echo "SHA-256 mismatch for $1: $got" >&2; exit 1; }
}
fetch MaterialIcons-Regular.ttf ef149f08bdd2ff09a4e2c8573476b7b0f3fbb15b623954ade59899e7175bedda
fetch MaterialIconsOutlined-Regular.otf b63fa9edd75e3c20328e04ad31dcc38ce76411f3f9ea1a1ff87f49e5ba874b05

# Filled: person star medical_services explore cell_tower directions_car
# visibility account_balance place person_pin_circle flag search warning_amber
# flight_land local_hospital emoji_people water_drop check_circle_outline
# flight waves router meeting_room sensors device_unknown navigation mic sos
# warning notifications_active
filled=0xE7FD,0xE838,0xF109,0xE87A,0xEBBA,0xE531,0xE8F4,0xE84F,0xE55F,0xE56A,0xE153,0xE8B6,0xF083
filled=$filled,0xE904,0xE548,0xEA1D,0xE798,0xE92D,0xE539,0xE176,0xE328,0xEB4F,0xE51E,0xE339,0xE55D
filled=$filled,0xE029,0xEBF7,0xE002,0xE7F7

npx --yes lv_font_conv@1.5.3 --size 14 --bpp 4 --format lvgl \
  --font "$work/MaterialIcons-Regular.ttf" -r "$filled" \
  --font "$work/MaterialIconsOutlined-Regular.otf" -r '0xE9E0=>0xF8E0' -r '0xE04B=>0xF8E1' -r '0xEA67=>0xF8E2' \
  --lv-include lvgl.h --lv-font-name map_icons_14 -o "$work/raw.c" >/dev/null

out="$repo_root/src/ui-touch/map_icons_14.c"
{
  echo "/* Material Icons (Apache-2.0, google/material-design-icons $rev), 14 px, 4 bpp."
  echo " * Generated by scripts/build/gen-map-icons.sh with lv_font_conv 1.5.3; do not edit. */"
  sed -e '/^ \* Opts:/d' "$work/raw.c"
} > "$out"
echo "wrote $out ($(wc -c < "$out") bytes of source)"
