// Draws the mark with its top-left corner at (x, y), through the display's
// writePixelsRGB565(x, y, w, h, pixels), one row per call.
template <class Display>
void wadameshDrawMark(Display& d, int x, int y) {
  uint16_t row[WADAMESH_MARK_W];
  int col = 0, r = 0;
  for (int i = 0; i < WADAMESH_MARK_RUNS && r < WADAMESH_MARK_H; i++) {
    const uint16_t c = WADAMESH_MARK_PALETTE[WADAMESH_MARK_RLE[2 * i]];
    for (int n = WADAMESH_MARK_RLE[2 * i + 1]; n > 0; n--) {
      row[col++] = c;
      if (col == WADAMESH_MARK_W) {
        d.writePixelsRGB565(x, y + r, WADAMESH_MARK_W, 1, row);
        col = 0;
        if (++r == WADAMESH_MARK_H) break;
      }
    }
  }
}
